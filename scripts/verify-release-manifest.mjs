// TASK-1763 — a release manifest that does not describe the installer beside it is
// the most dangerous artifact this repo can produce: it is well-formed, uploads
// cleanly, and silently points every auto-updating client at a file that is not
// there. Nothing downstream validates it, so this is the last place it can be caught.
//
// Recomputes sha512 from the actual bytes rather than trusting the manifest to
// describe itself — a manifest is exactly the thing you cannot take at its word here.

import * as fs from 'node:fs';
import * as path from 'node:path';
import * as crypto from 'node:crypto';

export function sha512Base64(bytes) {
  return crypto.createHash('sha512').update(bytes).digest('base64');
}

// Deliberately a hand-rolled reader for the three fields we care about rather than a
// YAML dependency: latest.yml is generated by electron-builder to a fixed shape, and
// adding a parser dependency to a release guard widens the thing it is guarding.
export function parseManifest(text) {
  // `\\s` not `\s`: inside a template literal `\s` collapses to a literal "s",
  // silently producing /^version:s*(.+)$/. That still "worked" here only because
  // `s*` matches zero characters and .trim() mopped up the leading space — a bug
  // that passes every test until a key ends in "s". Caught by eslint, not by us.
  const pick = (key) => text.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]?.trim();
  const size = text.match(/^\s+size:\s*(\d+)$/m)?.[1];
  return {
    version: pick('version'),
    path: pick('path'),
    sha512: pick('sha512'),
    size: size === undefined ? undefined : Number(size),
  };
}

// Pure so it is testable without touching a 196 MB file.
export function compareManifest({ manifest, pkgVersion, actualSha512, actualSize }) {
  const problems = [];
  if (manifest.version !== pkgVersion) {
    problems.push(`version mismatch: latest.yml says ${manifest.version}, package.json says ${pkgVersion} — this is the stale-manifest case`);
  }
  if (actualSha512 !== undefined && manifest.sha512 !== actualSha512) {
    problems.push(`sha512 mismatch: manifest does not describe the installer on disk`);
  }
  if (actualSize !== undefined && manifest.size !== actualSize) {
    problems.push(`size mismatch: manifest says ${manifest.size}, installer is ${actualSize} bytes`);
  }
  return { ok: problems.length === 0, problems };
}

export function verifyRelease({ releaseDir, pkgVersion }) {
  const ymlPath = path.join(releaseDir, 'latest.yml');
  if (!fs.existsSync(ymlPath)) {
    return { ok: false, problems: [`no latest.yml in ${releaseDir} — nothing to publish against`] };
  }
  const manifest = parseManifest(fs.readFileSync(ymlPath, 'utf8'));
  if (!manifest.path) return { ok: false, problems: ['latest.yml has no `path:` naming its installer'] };

  const exe = path.join(releaseDir, manifest.path);
  if (!fs.existsSync(exe)) {
    // The exact production failure: manifest names an asset that is not there.
    return { ok: false, problems: [`latest.yml names ${manifest.path}, which does not exist in ${releaseDir}`] };
  }
  const bytes = fs.readFileSync(exe);
  return compareManifest({
    manifest,
    pkgVersion,
    actualSha512: sha512Base64(bytes),
    actualSize: bytes.length,
  });
}

if (process.argv[1]?.endsWith('verify-release-manifest.mjs')) {
  const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
  const pkgVersion = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  const { ok, problems } = verifyRelease({ releaseDir: path.join(root, 'release'), pkgVersion });
  if (!ok) {
    console.error('[verify-release-manifest] REFUSING to treat this release as publishable:\n');
    for (const p of problems) console.error(`  - ${p}`);
    console.error('\nA manifest that misdescribes its installer breaks auto-update silently.');
    process.exit(1);
  }
  console.log(`[verify-release-manifest] latest.yml matches package.json ${pkgVersion} and the installer bytes on disk.`);
}
